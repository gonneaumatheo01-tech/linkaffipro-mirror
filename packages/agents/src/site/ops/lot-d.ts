type Schema = Record<string, unknown>;
const s = (description: string, extra: Schema = {}): Schema => ({ type: "string", description, ...extra });
const n = (description: string, minimum?: number, maximum?: number): Schema => ({
  type: "number",
  description,
  ...(minimum !== undefined ? { minimum } : {}),
  ...(maximum !== undefined ? { maximum } : {}),
});
const i = (description: string, minimum?: number, maximum?: number): Schema => ({ ...n(description, minimum, maximum), type: "integer" });
const b = (description: string): Schema => ({ type: "boolean", description });
const list = (description: string): Schema => ({ type: "array", items: { type: "string" }, description });
const oneOf = (description: string, values: string[]): Schema => ({ type: "string", enum: values, description });
const obj = (properties: Record<string, Schema>, required: string[] = []): Schema => ({
  type: "object",
  properties,
  ...(required.length ? { required } : {}),
  additionalProperties: false,
});
const nullable = (x: Schema): Schema => ({ ...x, type: [x.type as string, "null"] });

